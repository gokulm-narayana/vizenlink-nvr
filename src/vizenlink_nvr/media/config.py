def render_yaml(cfg: dict[str, Any]) -> str:
    """Render configuration dictionary as YAML with required header comment."""
    content = yaml.dump(cfg, sort_keys=False, default_flow_style=False)
    return f"# Generated by vizenlink-nvr. Do not edit.\n{content}"


def write_config(path: Path, cfg: dict[str, Any]) -> None:
    """Write configuration file with restricted permissions (0600 on POSIX)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    rendered = render_yaml(cfg)
    path.write_text(rendered, encoding="utf-8")
    if os.name == "posix":
        os.chmod(path, 0o600)
