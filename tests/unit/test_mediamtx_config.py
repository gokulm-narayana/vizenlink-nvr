EXPECTED_ADDRESS_KEYS = {
    "apiAddress",
    "metricsAddress",
    "pprofAddress",
    "playbackAddress",
    "rtspAddress",
    "rtspsAddress",
    "rtpAddress",
    "rtcpAddress",
    "srtpAddress",
    "srtcpAddress",
    "hlsAddress",
    "webrtcAddress",
    "webrtcLocalUDPAddress",
    "webrtcLocalTCPAddress",
    "rtmpAddress",
    "rtmpsAddress",
    "srtAddress",
    "moqHTTP2Address",
    "moqHTTP3Address",
    "moqQUICAddress",
}


def test_build_config_security_defaults() -> None:
    """Config has no 'any' user, control user is api-only on loopback, and unused protocols are disabled."""
    pw = "secret-control-pass"
    pw_hash = hash_control_password(pw)
    assert pw not in pw_hash
    assert pw_hash.startswith("sha256:")

    ports = MediaMtxPorts(api=19997, playback=19996, rtsp=18554, hls=18888, webrtc=18889, webrtc_udp=18189)
    cfg = build_config(ports, pw_hash)

    # Authentication
    assert cfg["authMethod"] == "internal"
    users = cfg["authInternalUsers"]
    assert len(users) == 1
    assert users[0]["user"] == CONTROL_USER
    assert users[0]["pass"] == pw_hash
    assert users[0]["ips"] == ["127.0.0.1/32", "::1/128"]
    assert users[0]["permissions"] == [{"action": "api"}]
    assert not any("any" in str(u).lower() for u in users)

    # Disabled protocols
    assert cfg["rtmp"] is False
    assert cfg["srt"] is False
    assert cfg["moq"] is False
    assert cfg["metrics"] is False
    assert cfg["pprof"] is False

    # CORS origins empty
    assert cfg["apiAllowOrigins"] == []
    assert cfg["playbackAllowOrigins"] == []
    assert cfg["hlsAllowOrigins"] == []
    assert cfg["webrtcAllowOrigins"] == []
    assert cfg["moqAllowOrigins"] == []

    # Recording defaults
    assert cfg["pathDefaults"]["record"] is False
    assert cfg["pathDefaults"]["recordFormat"] == "fmp4"
    assert cfg["pathDefaults"]["recordDeleteAfter"] == "0s"

    # Transport settings
    assert cfg["rtspTransports"] == ["tcp"]
    assert cfg["webrtcIPsFromInterfaces"] is False
    assert cfg["webrtcAdditionalHosts"] == ["127.0.0.1"]


def test_every_listener_address_explicit_loopback() -> None:
    """Every address key defined in MediaMTX is explicitly bound to 127.0.0.1."""
    pw_hash = hash_control_password("dummy")
    cfg = build_config(MediaMtxPorts(), pw_hash)

    found_address_keys: set[str] = set()

    def _walk(obj: Any) -> None:
        if isinstance(obj, dict):
            for k, v in obj.items():
                if "Address" in k:
                    found_address_keys.add(k)
                    assert isinstance(v, str), f"{k} value must be string: {v}"
                    assert v.startswith("127.0.0.1:"), f"{k} value {v} must start with 127.0.0.1:"
                _walk(v)
        elif isinstance(obj, list):
            for item in obj:
                _walk(item)

    _walk(cfg)

    # Assert exact expected address keys are all present and validated
    assert found_address_keys == EXPECTED_ADDRESS_KEYS


def test_render_and_write_config(tmp_path: Path) -> None:
    """Config renders with required header comment and writes with 0600 permissions on POSIX."""
    pw_hash = hash_control_password("dummy")
    cfg = build_config(MediaMtxPorts(), pw_hash)

    rendered = render_yaml(cfg)
    assert rendered.startswith("# Generated by vizenlink-nvr. Do not edit.\n")

    # Round trip YAML validation
    parsed = yaml.safe_load(rendered)
    assert parsed["authMethod"] == "internal"
    assert parsed["apiAddress"] == "127.0.0.1:9997"

    target_file = tmp_path / "mediamtx.yml"
    write_config(target_file, cfg)

    assert target_file.exists()
    assert target_file.read_text(encoding="utf-8") == rendered

    if os.name == "posix":
        mode = target_file.stat().st_mode & 0o777
        assert mode == 0o600
